export const getText = (key, lang = 'en') => {
  if (!key) return '';
  const parts = key.split('.');
  let current = UI_TEXT;
  for (const p of parts) {
    if (!current[p]) return UI_TEXT[parts[0]]?.[lang] || UI_TEXT[parts[0]]?.['en'] || key;
    current = current[p];
  }
  return current[lang] || current['en'] || key;
};
